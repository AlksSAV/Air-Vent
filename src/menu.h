#ifndef MENU_H
#define MENU_H

#include <Arduino.h>
#include <LiquidCrystal.h>

// Меню настроек: два уровня, три раздела.
//   TEMP  — пределы наружного воздуха
//   VALVE — наличие привода и длительность импульса
//   MISC  — сброс наработки и версия прошивки
//
// Клавиши внутри меню:
//   Up / Down      — перемещение по пунктам
//   Left / Right   — изменение выбранного значения
//   Select коротко — войти в раздел (в главном), выйти на уровень выше
//   Select удержать— назад; на пункте RESET RT — сброс наработки

// Открыть меню с главной страницы.
void menu_open();

// Обработать клавиши и обновить значения. Возвращает false, когда меню
// закрыто и управление пора вернуть обычным экранам.
bool menu_update();

// Нарисовать текущую страницу меню.
void menu_draw(LiquidCrystal& lcd);

#endif  // MENU_H
